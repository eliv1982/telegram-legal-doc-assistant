"""
Лимиты приёма и обработки файлов. Все значения собраны здесь, чтобы их можно было прочитать и обосновать
в одном месте. Модули читают их как `limits.NAME` в момент вызова (не через `from ... import`),
поэтому тесты могут временно подменять значения.

Различаем три понятия:
  - файл принят            -> прошёл проверки ниже;
  - страниц доступно       -> сколько их в PDF (не больше MAX_PDF_PAGES);
  - страниц проанализировано -> не больше MAX_ANALYSED_PAGES. Это единственное, что видит модель.
"""

# --- Размер загрузки -------------------------------------------------------------------------------------
# 20 MiB — потолок скачивания файлов у облачного Bot API Telegram; проверка у нас остаётся источником истины
# (и для локального Bot API сервера, и для файла, чей размер Telegram не сообщил).
MAX_UPLOAD_BYTES = 20 * 1024 * 1024

# --- Изображения -----------------------------------------------------------------------------------------
# 40 Мпикс (например 8000x5000) — это уже ~120 МБ в памяти после декодирования; больше фото документа не нужно.
MAX_IMAGE_PIXELS = 40_000_000
# Слишком маленькая картинка не содержит читаемого документа: не тратим на неё платный вызов Vision.
MIN_IMAGE_SIDE_PX = 32
# Vision всё равно уменьшает изображение (длинная сторона <= 2048), поэтому большее разрешение только раздувает запрос.
MAX_IMAGE_SIDE_PX = 2048
JPEG_QUALITY = 90

# --- PDF: структура --------------------------------------------------------------------------------------
# Принимаем до 20 страниц, анализируем меньше (см. ниже): так пользователь не получает отказ на 12-страничный
# договор, но и не платит за разбор 20 страниц.
MAX_PDF_PAGES = 20
# Физический размер страницы в пунктах (1 pt = 1/72 дюйма). A4 = 595x842, A0 = 2384x3370; спецификация PDF
# допускает до 14400. Меньше 36 pt (полдюйма) — не документ, больше 3600 pt (50 дюймов) — не документ.
MIN_PAGE_POINTS = 36.0
MAX_PAGE_POINTS = 3600.0

# --- PDF: рендеринг (Poppler) ----------------------------------------------------------------------------
# Длинная сторона отрендеренной страницы. Poppler получает `-scale-to`, поэтому размер растра ограничен
# сверху MAX_IMAGE_SIDE_PX x MAX_IMAGE_SIDE_PX независимо от того, что написано в MediaBox.
RENDER_LONG_SIDE_PX = MAX_IMAGE_SIDE_PX
# Тайм-аут на каждый вызов Poppler (pdfinfo и pdftoppm), секунды. Обычная страница рендерится за доли секунды.
RENDER_TIMEOUT_SECONDS = 20
# Результат рендеринга с короче стороной — подозрительный (например, лист 3600x36 pt даёт полоску 2048x20).
MIN_RENDER_SIDE_PX = 32
# Страница считается пустой, если разница между самым тёмным и самым светлым пикселем не больше этого значения.
BLANK_CONTRAST = 12

# --- Охват анализа ---------------------------------------------------------------------------------------
# Сколько страниц реально читается (текстовый слой или Vision). Остальное честно помечается как непроанализированное.
MAX_ANALYSED_PAGES = 5
# Страница, у которой текстового слоя меньше стольких непробельных символов, считается «сканом» и уходит в Vision.
MIN_PAGE_TEXT_CHARS = 40
# Потолок текста одной страницы (плотная страница договора — 3–5 тыс. символов).
MAX_PAGE_CHARS = 6_000
# Потолок текста, который уходит в анализ. Должен вмещать MAX_ANALYSED_PAGES страниц по MAX_PAGE_CHARS
# вместе с маркерами страниц; тест проверяет это неравенство. Так срез в OpenAIService.analyze_document
# никогда не отрезает уже засчитанные страницы.
ANALYSIS_CHAR_LIMIT = 32_000
